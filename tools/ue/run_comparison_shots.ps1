# The comparison screenshots shared with the browser client (meridian-browser
# tools/screenshots/shots.json and README.md): every shot that lists "unreal", taken from the same
# server square and facing as the browser's Classic, Modern and phone shots, with the HUD on and
# the player wielding a mace and wearing a shield. Offline: no server needed.
#
#   powershell -File tools/ue/run_comparison_shots.ps1
#   powershell -File tools/ue/run_comparison_shots.ps1 -Only raza-pond,inn-room
#
# It turns the shots into look-dev cameras (data/environment/comparison_cameras.json, generated
# and git-ignored), with each square's centre converted as in AGENTS.md (zones and coordinates),
# and runs the look-dev tour (run_lookdev.ps1) with:
#   -WithPawn             through the player's own eyes
#   -MRLookDevUI          the HUD in the picture; "steps" open the inventory or show the login screen
#   -MRLookDevWield=2     the offline inventory's mace (data/ui/mock_inventory.json, hotbar slot 3)
#   -MRSpriteEquip=...    the mace and the metal shield on the character's sprite
# The images are copied to <browser>/ReferenceImages/comparisons/<id>/unreal.png beside the others.
param(
    [string]$Manifest = "",
    [string[]]$Only = @(),
    [string]$Out = "",
    [string]$Label = "comparison",
    # the browser shots pin "afternoon"; 17 is where the afternoon mood was tuned (run_lookdev.ps1)
    [double]$GameHour = 17,
    [int]$ResX = 1600,
    [int]$ResY = 900,
    [string]$Engine = "G:\Unreal Engine\UE_5.8\Engine\Binaries\Win64\UnrealEditor.exe"
)

$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$browser = Join-Path (Split-Path -Parent $repo) "meridian-browser"
if (-not $Manifest) { $Manifest = Join-Path $browser "tools\screenshots\shots.json" }
if (-not $Out) { $Out = Join-Path $browser "ReferenceImages\comparisons" }
if (-not (Test-Path $Manifest)) { Write-Host "FAIL: no shot list at $Manifest (-Manifest)"; exit 1 }

$shots = (Get-Content -Raw $Manifest | ConvertFrom-Json).shots | Where-Object { $_.clients -contains "unreal" }
if ($Only) {
    $Only = $Only | ForEach-Object { $_ -split "," } | Where-Object { $_ }
    $shots = $shots | Where-Object { $Only -contains $_.id }
}
if (-not $shots) { Write-Host "FAIL: no shots for unreal"; exit 1 }

$layout = Get-Content -Raw (Join-Path $repo "data\zone_layout.json") | ConvertFrom-Json
$cmPerRoo = 0.21484375
$cameras = @()
foreach ($s in $shots) {
    $steps = @($s.steps | Where-Object { $_ })
    if ($s.PSObject.Properties.Name -contains "unreal") {
        # a camera of its own (the login screen's: the square, as the online login flies over it)
        $u = $s.unreal
        $cameras += [ordered]@{ name = $s.id; location_cm = $u.location_cm; rotation = $u.rotation; fov = $u.fov; steps = $steps }
        continue
    }
    $zone = $layout.zones | Where-Object { $_.rid -eq $s.rid } | Select-Object -First 1
    if (-not $zone) { Write-Host "FAIL: $($s.id): room $($s.rid) isn't in data/zone_layout.json"; exit 1 }
    # the square's centre in ROO units (roo = (kod - 64) * 16, kod = square * 64 + 32), then UE cm
    $x = $zone.world_origin_cm[0] + (($s.col - 1) * 1024 + 512) * $cmPerRoo
    $y = $zone.world_origin_cm[1] + (($s.row - 1) * 1024 + 512) * $cmPerRoo
    # a point at head height above the zone's arrival floor: the tour traces down to the floor from it
    $z = $zone.world_origin_cm[2] + $zone.teleport.pos[1] * 100 + 150
    $yaw = $s.angle * 360.0 / 4096
    if ($yaw -gt 180) { $yaw -= 360 }
    $cameras += [ordered]@{
        name = $s.id
        location_cm = @([math]::Round($x), [math]::Round($y), [math]::Round($z))
        rotation = @(0, [math]::Round($yaw, 1))
        fov = 90
        stand = $true
        steps = $steps
    }
}
$camFile = Join-Path $repo "data\environment\comparison_cameras.json"
$doc = [ordered]@{ _doc = "Generated by tools/ue/run_comparison_shots.ps1 from meridian-browser tools/screenshots/shots.json; don't edit."; cameras = $cameras }
[System.IO.File]::WriteAllText($camFile, ($doc | ConvertTo-Json -Depth 6), (New-Object System.Text.UTF8Encoding($false)))

$extra = "-MRLookDevUI -MRLookDevWield=2 -MRSpriteEquip=maceov@22:4,metlshld@32:2"
& (Join-Path $PSScriptRoot "run_lookdev.ps1") -Label $Label -Cameras "comparison_cameras.json" -WithPawn `
    -GameHour $GameHour -ResX $ResX -ResY $ResY -Engine $Engine -Extra $extra
if ($LASTEXITCODE -ne 0 -and $LASTEXITCODE -ne $null) { exit $LASTEXITCODE }

$taken = Join-Path $repo "build\lookdev\$Label"
$n = 0
foreach ($s in $shots) {
    $png = Join-Path $taken "$($s.id).png"
    if (-not (Test-Path $png)) { Write-Host "missing: $($s.id)"; continue }
    $dir = Join-Path $Out $s.id
    New-Item -ItemType Directory -Force $dir | Out-Null
    Copy-Item -Force $png (Join-Path $dir "unreal.png")
    Write-Host "  $($s.id) -> $(Join-Path $dir 'unreal.png')"
    $n++
}
Write-Host "$n comparison shot(s) in $Out"
