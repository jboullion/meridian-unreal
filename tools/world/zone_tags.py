"""
Ground types and biomes (docs/adr/0003 "Ground types and biomes"): what each floor texture is (grass,
dirt, rock, sand, paving, wood...) and what kind of place each room is (city, forest, mountain, cave,
sewer, dungeon, island...), so ground and ambient effects can be set by type rather than room by room.

    python tools/world/zone_tags.py          # -> data/world/zone_tags.json
    npm run tags

Rules and hand overrides: data/world/tags.json. Reads:
- build/textures/catalog.json (texture names);
- data/net/rooms.json (every Kod room and its terrain flags, TERRAIN_*), data/zones.json (the built
  rooms' outside factor), data/world/maps.json (each map's region and pass);
- build/environment/zone_<rid>/textures.json (tools/environment/zone_textures.py: a built zone's floors
  and their areas) and data/environment/moods.json (its kind: outdoor, interior or underground).
Rooms not built yet get a biome from their terrain flags and region alone, and no ground.
"""
from __future__ import annotations

import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def load(*parts, default=None):
    path = os.path.join(REPO, *parts)
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    rules = load("data", "world", "tags.json")
    ground_rules = [(re.compile(p, re.I), t) for p, t in rules["ground_types"]["rules"]]
    catalog = load("build", "textures", "catalog.json", default={"textures": {}})["textures"]
    rooms = load("data", "net", "rooms.json")["rooms"]
    zones = {z["rid"]: z for z in load("data", "zones.json", default=[])}
    moods = load("data", "environment", "moods.json")["zones"]
    maps = load("data", "world", "maps.json", default={"maps": []})["maps"]
    maps = maps.values() if isinstance(maps, dict) else maps
    region_of = {}
    for m in maps:
        for r in m["rooms"]:
            if r.get("rid") is not None:
                region_of[r["rid"]] = (m["roo"], m["region"], m["pass"])

    def ground_type(grd):
        if grd in rules.get("ground_overrides", {}):
            return rules["ground_overrides"][grd]
        name = (catalog.get(grd) or {}).get("name") or ""
        return next((t for p, t in ground_rules if p.search(name)), "other")

    def biome(rid, kind, terrain, region):
        if str(rid) in rules.get("biome_overrides", {}):
            return rules["biome_overrides"][str(rid)]
        for r in rules["biomes"]["rules"]:
            if "terrain_any" in r and not set(r["terrain_any"]) & set(terrain):
                continue
            if "kind" in r and kind not in r["kind"]:
                continue
            if "region_any" in r and not any(w.lower() in (region or "").lower() for w in r["region_any"]):
                continue
            return r["biome"]
        return "unknown"

    textures, out_rooms = {}, {}
    for room in rooms:
        rid = room["rid"]
        flags = room.get("terrain") or (zones.get(rid) or {}).get("terrain") or []  # zones.json: built rooms
        terrain = [t.removeprefix("TERRAIN_").lower() for t in flags]
        roo, region, pass_no = region_of.get(rid, (room["roo"].lower().removesuffix(".roo"), None, None))
        entry = {"class": room["class"], "name": room.get("name"), "map": roo, "region": region, "pass": pass_no,
                 "terrain": terrain}
        built = rid in zones and os.path.exists(os.path.join(REPO, "build", "environment", "zone_%d" % rid, "textures.json"))
        kind = None
        if built:
            prof = moods.get(str(rid))
            kind = prof.get("kind", "outdoor") if prof else "outdoor"  # no profile: moods.json "default", outdoor (Raza)
            floors = {}
            for t in load("build", "environment", "zone_%d" % rid, "textures.json"):
                if t["where"] != "floor" or not t["grd"].startswith("grd") or t["kind"] in ("animated",):
                    continue
                g = ground_type(t["grd"])
                textures.setdefault(t["grd"], {"name": (catalog.get(t["grd"]) or {}).get("name"), "ground": g, "rooms": []})["rooms"].append(rid)
                floors[g] = round(floors.get(g, 0) + t["area_m2"], 1)
            entry["ground_m2"] = dict(sorted(floors.items(), key=lambda kv: -kv[1]))
        entry["kind"] = kind
        entry["biome"] = biome(rid, kind, terrain, region)
        entry["built"] = built
        out_rooms[str(rid)] = entry

    out = {"_doc": "Generated by tools/world/zone_tags.py from data/world/tags.json (edit the rules and overrides there): "
                   "textures: every floor texture of a built zone, its ground type and the rooms it floors; rooms: every Kod "
                   "room, its terrain flags (the original's TERRAIN_*), kind, biome, and for built zones its floor area per ground type (m2).",
           "textures": dict(sorted(textures.items())), "rooms": out_rooms}
    with open(os.path.join(REPO, "data", "world", "zone_tags.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write("\n")
    by_biome, by_ground = {}, {}
    for e in out_rooms.values():
        by_biome[e["biome"]] = by_biome.get(e["biome"], 0) + 1
    for t in textures.values():
        by_ground[t["ground"]] = by_ground.get(t["ground"], 0) + 1
    print("rooms: %d (%d built); biomes %s" % (len(out_rooms), sum(e["built"] for e in out_rooms.values()),
                                               dict(sorted(by_biome.items(), key=lambda kv: -kv[1]))))
    print("floor textures: %d; ground types %s" % (len(textures), dict(sorted(by_ground.items(), key=lambda kv: -kv[1]))))
    print("wrote data/world/zone_tags.json")


if __name__ == "__main__":
    main()
